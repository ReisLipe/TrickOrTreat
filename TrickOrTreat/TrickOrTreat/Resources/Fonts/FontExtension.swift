import SwiftUI

extension Font {

    static func sigmar(size: CGFloat) -> Font {
        return .custom("Sigmar", size: size)
    }
    
    static func sil(size: CGFloat) -> Font {
        return .custom("ShadowsIntoLight", size: size)
    }
}
